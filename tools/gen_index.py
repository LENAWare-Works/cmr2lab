#!/usr/bin/env python3
"""gen_index.py -- regenerate docs/INDEX.md from the actual file tree.

Written 2026-10-15 after finding INDEX.md listing 41 of 50 documents: the old
one was hand-maintained and drifted silently, which is worse than no index
because it reads as complete.

Run from the repository root:

    python3 tools/gen_index.py

Every .md under docs/ is listed. Descriptions are the first prose line of each
file, so a document that changes its opening line updates its own index entry.
Nothing here is hand-written, so nothing here can go stale without the file
itself having moved.

Exit code 1 if a document has no readable description, so a malformed file
cannot quietly become a blank row.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, 'docs')

# Ordering matters for a reader; anything not named here falls into "More".
SECTIONS = [
    ("Start here", ["README.md", "STATUS.md", "GLOSSARY.md", "INDEX.md"]),
    ("Using it", ["INSTALLER.md", "CONTROLS.md", "MODES.md"]),
    ("Formats and internals", ["CAR.md", "C3D.md", "CONTAINER.md", "ART-PROVENANCE.md"]),
    ("The car renderer", ["RENDER.md", "RENDER-OPEN-BUGS.md"]),
    ("Fixes that shipped", ["FIXES-20261011.md", "GPU-LIFETIME-FIX.md",
                            "DXT-COPY-PATH.md", "DRIVE-LOOP-REGRESSION.md",
                            "ROAD-TEXTURE-OWNER.md", "LAUNCHER-DEAD-BUILD.md"]),
    ("Open problems, measured", ["DEATH-AND-LIGHT.md", "AMBIENT-CONTRADICTION-RESOLVED.md",
                                 "FOG-VERIFIED-SPEC.md", "ROAD-r6-REPORT.md",
                                 "MENU-CAR.md", "MENU-CAR-EVIDENCE.md", "WHITE-CARD.md",
                                 "HUD-2D.md", "FRAMING.md", "DRAW-CENSUS-RACE.md",
                                 "CAMERA-AND-NEAR-PLANE.md", "S2-CENSUS.md",
                                 "NOISE-20261012.md", "FRAME-NOTE.md"]),
    ("The port", ["PORT.md", "PORT-PLAN.md", "PLAY-CHECKPOINT.md",
                  "RUNTIME-RELAY.md", "DEPENDENCY-MAP.md", "DECK-UI-CONSTRAINT.md"]),
    ("Plans", ["WHERE-THIS-IS-GOING.md"]),
]


def first_prose(path):
    """The first line that is actually a sentence, not a heading or a rule."""
    try:
        with open(path, errors='ignore') as fh:
            for raw in fh:
                line = raw.strip()
                if not line:
                    continue
                if line[0] in '#>|![' or line.startswith('---'):
                    continue
                if line.startswith('```'):
                    continue
                text = re.sub(r'[`*_]', '', line)
                return text[:160] + ('…' if len(text) > 160 else '')
    except OSError:
        return ''
    return ''


def main():
    names = sorted(f for f in os.listdir(DOCS) if f.endswith('.md'))
    desc = {}
    missing = []
    for n in names:
        d = first_prose(os.path.join(DOCS, n))
        if not d:
            missing.append(n)
        desc[n] = d or '_no description — add a prose first line_'

    seen = set()
    sections = []
    for title, wanted in SECTIONS:
        have = [w for w in wanted if w in names]
        seen.update(have)
        if have:
            sections.append((title, have))
    rest = [n for n in names if n not in seen]
    if rest:
        sections.append(("More", rest))

    out = [
        "# Every document in this repo",
        "",
        "Generated by [`tools/gen_index.py`](../tools/gen_index.py) — **do not hand-edit**.",
        "The previous version of this file was maintained by hand and listed 41 of the 50",
        "documents in `docs/`, which is worse than no index because it reads as complete.",
        "",
        "Re-run after adding or renaming a document:",
        "",
        "```sh",
        "python3 tools/gen_index.py",
        "```",
        "",
        "A document's description is its own first prose line, so it updates itself.",
        "",
        "---",
        "",
    ]
    for title, files in sections:
        out += ["## %s" % title, "", "| document | first line |", "|---|---|"]
        for n in files:
            out.append("| [`%s`](%s) | %s |" % (n, n, desc[n].replace('|', r'\|')))
        out.append("")

    out += [
        "---", "",
        "## Not in this directory", "",
        "| | |", "|---|---|",
        "| [`../README.md`](../README.md) | the front door and the honest status table |",
        "| [`../progress.md`](../progress.md) | the live status page, rewritten whole each round |",
        "| [`../archive/`](../archive/README.md) | superseded round logs and delivered notes — nothing deleted |",
        "| [`../frames/`](../frames/) | raw captures, each directory with a README naming its binary and run |",
        "",
    ]

    with open(os.path.join(DOCS, 'INDEX.md'), 'w') as fh:
        fh.write('\n'.join(out))

    print("gen_index: %d documents across %d sections" % (len(names), len(sections)))
    if missing:
        print("WARNING: no prose first line in: %s" % ', '.join(missing))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
